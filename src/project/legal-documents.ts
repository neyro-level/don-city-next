export function getProjectLegalDocument(
	slug: string,
	nap: PublicNapDTO,
): ProjectLegalDocument | undefined {
	if (slug === projectLegalSlugs[0]) return privacyPolicy(nap);
	if (slug === projectLegalSlugs[1]) return personalDataConsent(nap);
	return undefined;
}
