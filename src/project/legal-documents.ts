import type { PublicNapDTO } from "@ams/realtbase-contracts";
import { companyProfile } from "./company-profile.ts";
import { legalConsentConfig } from "./legal.config.ts";

export const projectLegalSlugs = [
	"politika-konfidencialnosti",
	"soglasie-na-obrabotku-personalnyh-dannyh",
] as const;

export type ProjectLegalSlug = (typeof projectLegalSlugs)[number];

export type ProjectLegalDocument = {
	id: string;
	slug: string;
	title: string;
	shortTitle: string;
	description: string;
	version: string;
	updatedAt: string;
	intro: readonly string[];
	sections: readonly {
		title: string;
		paragraphs?: readonly string[];
		items?: readonly string[];
	}[];
};

const updatedAt = "25 сентября 2026 г.";

function operatorDetails(nap: PublicNapDTO) {
	return `${nap.legalName}, ИНН ${companyProfile.inn}, ОГРНИП ${companyProfile.ogrnip} от ${companyProfile.ogrnipAssignedAt}, адрес: ${companyProfile.legalAddress}`;
}

