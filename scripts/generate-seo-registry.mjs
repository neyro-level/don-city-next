import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { buildProjectUrl } from "../src/project/url-grammar.ts";

const root = resolve(import.meta.dirname, "..");
const csvPath = resolve(root, "docs/seo/SEO_REGISTRY_SEED.csv");
const outputPath = resolve(root, "src/project/seo-registry.generated.ts");
const write = process.argv.includes("--write");

function parseCsv(input) {
	const rows = [];
	let row = [];
	let value = "";
	let quoted = false;
	for (let index = 0; index < input.length; index += 1) {
		const character = input[index];
		if (quoted) {
			if (character === '"' && input[index + 1] === '"') {
				value += '"';
				index += 1;
			} else if (character === '"') quoted = false;
			else value += character;
		} else if (character === '"') quoted = true;
		else if (character === ",") {
			row.push(value);
			value = "";
		} else if (character === "\n") {
			row.push(value.replace(/\r$/, ""));
			rows.push(row);
			row = [];
			value = "";
		} else value += character;
	}
	if (quoted) throw new Error("Unterminated CSV quote");
	if (value || row.length) {
		row.push(value.replace(/\r$/, ""));
		rows.push(row);
	}
	const [headers, ...data] = rows.filter((entry) => entry.some(Boolean));
	return {
		headers,
		rows: data.map((entry) =>
			Object.fromEntries(
				headers.map((header, index) => [header, entry[index] ?? ""]),
			),
		),
	};
}

const categorySlugs = {
	apartment: "kvartiry",
	house: "doma",
	land: "uchastki",
};

const staticKeys = {
	HOME: { kind: "home" },
	SELL: { kind: "static", slug: "prodat-nedvizhimost" },
	LAW: { kind: "static", slug: "yurist" },
	ABOUT: { kind: "static", slug: "o-kompanii" },
	CONTACTS: { kind: "static", slug: "kontakty" },
	PRIVACY: { kind: "static", slug: "politika-konfidencialnosti" },
	CONSENT: {
		kind: "static",
		slug: "soglasie-na-obrabotku-personalnyh-dannyh",
	},
	THANKS: { kind: "static", slug: "spasibo" },
};

function pageKeyFor(row) {
	if (staticKeys[row.registryId]) return staticKeys[row.registryId];
	const category = categorySlugs[row.category];
	switch (row.pageType) {
		case "geo_all":
			return { kind: "geoHub", geo: row.geoSlug };
		case "category_root":
			return { kind: "categoryRoot", category };
		case "category_geo":
			return { kind: "categoryGeo", geo: row.geoSlug, category };
		case "district":
			return {
				kind: "categoryGeoDistrict",
				geo: row.geoSlug,
				category,
				district: row.districtSlug,
			};
		case "facet":
			return {
				kind: "categoryGeoFacet",
				geo: row.geoSlug,
				category,
				facet: row.facetSlug,
			};
		default:
			throw new Error(`Unsupported SEO row: ${row.registryId}/${row.pageType}`);
	}
}

function quoteCsv(value) {
	return `"${String(value).replaceAll('"', '""')}"`;
}

function serializeCsv(headers, rows) {
	return `${headers.join(",")}\n${rows
		.map((row) =>
			headers.map((header) => quoteCsv(row[header] ?? "")).join(","),
		)
		.join("\n")}\n`;
}

function renderModule(rows) {
	return `// Generated by scripts/generate-seo-registry.mjs. Do not edit directly.\nimport type { SeoRegistryEntry } from "../platform/seo/registry.ts";\n\nexport const seoRegistry = ${JSON.stringify(rows, null, "\t")} as const satisfies readonly SeoRegistryEntry[];\n\nexport const seoRegistryByCanonicalPath = new Map<string, SeoRegistryEntry>(\n\tseoRegistry.map((entry) => [entry.url, entry]),\n);\n\nexport const seoRegistryById = new Map<string, SeoRegistryEntry>(\n\tseoRegistry.map((entry) => [entry.registryId, entry]),\n);\n`;
}

const source = await readFile(csvPath, "utf8");
const csv = parseCsv(source);
const rows = csv.rows.map((row) => ({
	...row,
	url: buildProjectUrl(pageKeyFor(row)),
}));
const expectedCsv = serializeCsv(csv.headers, rows);
const expectedModule = renderModule(rows);

if (write) {
	await Promise.all([
		writeFile(csvPath, expectedCsv, "utf8"),
		writeFile(outputPath, expectedModule, "utf8"),
	]);
	console.log(`SEO registry generated: ${rows.length} rows`);
} else {
	assert.equal(
		source.replaceAll("\r\n", "\n"),
		expectedCsv,
		"SEO CSV URLs drifted from V4 grammar",
	);
	const actualModule = await readFile(outputPath, "utf8");
	assert.equal(
		actualModule,
		expectedModule,
		"Generated SEO runtime registry is stale",
	);
	console.log(`SEO registry generation check PASS: ${rows.length} rows`);
}
